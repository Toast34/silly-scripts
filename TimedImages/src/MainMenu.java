    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {
        if (evt.getSource() == this.jButton1) {
            if (Objects.equals(jButton1.getText(), "Start")) {
                thread = new Worker(settings.getFileName());
                timer = new Timer();
                timer.schedule(thread, 5, 1000 * 60 * (long) (int) settings.getjSpinner2().getValue());
                jButton1.setText("Stop");
            } else {
                timer.cancel();
                jButton1.setText("Start");
            }
        }
    }

